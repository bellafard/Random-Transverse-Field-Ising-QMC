#!/bin/bash

ctr=$RANDOM

date >> log

for l in \
8,2 8,4 8,8 8,12 8,16 8,20 8,24 8,32 8,40 8,48 \
16,2 16,4 16,8 16,12 16,16 16,20 16,24 16,32 16,40 16,48 16,56 16,64 16,80 16,96 \
32,2 32,4 32,8 32,12 32,16 32,20 32,24 32,32 32,40 32,48 32,56 32,64 32,80 32,96 32,128 32,160 32,192 \
64,2 64,4 64,8 64,12 64,16 64,20 64,24 64,32 64,40 64,48 64,56 64,64 64,80 64,96 64,128 64,160 64,192 64,256 64,320 64,384 \
128,2 128,4 128,8 128,12 128,16 128,20 128,24 128,32 128,40 128,48 128,56 128,64 128,80 128,96 128,128 128,160 128,192 128,256 128,320 128,384 128,512 128,640 128,768 \
256,2 256,4 256,8 256,12 256,16 256,20 256,24 256,32 256,40 256,48 256,56 256,64 256,80 256,96 256,128 256,160 256,192 256,256 256,320 256,384 256,512 256,640 256,768 256,896 256,1024 256,1280 256,1536; do
	IFS=","; set $l; lx=$1; lt=$2

	sed -e 's/lxv/'$lx'/' < at.cc > tmp.cc
	sed -i 's/ltv/'$lt'/' tmp.cc

	sleep 1s
	let ctr++

	g++ tmp.cc -o ."$ctr"
	
	job.q -m error -ns ."$ctr" > /dev/null

	if [[ $lx -lt 96 ]]; then
		echo qsub -m n -l h_data=2G,h_rt=24:00:00 ."$ctr".cmd #>> log &
	else
		echo qsub -m n -l h_data=4G,h_rt=24:00:00 ."$ctr".cmd #>> log &
	fi
	
	echo L = "$lx"x"$lt" is processed. >> log
done
echo >> log

rm -f .tmp*
